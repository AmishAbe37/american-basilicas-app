"""Copy the website's basilica photos into the app at phone size, so they work with no signal.
Usage: python3 tools/build-photos.py <path to the american-basilicas website repo>
Writes assets/photos/<id>.jpg (720 px wide, metadata stripped) and src/data/photos.ts."""
import sys, json, pathlib
from PIL import Image
SITE = pathlib.Path(sys.argv[1]); ROOT = pathlib.Path(__file__).resolve().parent.parent
ids = [b["id"] for b in json.load(open(ROOT / "assets/data/basilicas.json"))]
out = ROOT / "assets/photos"; out.mkdir(parents=True, exist_ok=True)
total = 0; missing = []; ratio = {}
for i in ids:
    src = SITE / "images" / f"{i}.jpg"
    if not src.exists(): missing.append(i); continue
    im = Image.open(src).convert("RGB")
    if im.width > 720: im = im.resize((720, round(im.height * 720 / im.width)), Image.LANCZOS)
    dst = out / f"{i}.jpg"; im.save(dst, "JPEG", quality=80, optimize=True, progressive=True)   # no EXIF copied
    total += dst.stat().st_size; ratio[i] = round(im.height / im.width, 4)
lines = ["// Generated by tools/build-photos.py. Do not edit by hand.", "export const PHOTOS: Record<string, number> = {"]
lines += [f'  "{i}": require("../../assets/photos/{i}.jpg"),' for i in ids if i not in missing]
lines += ["};", "", "/** Height / width of each photo, so screens can size them before they load. */", "export const PHOTO_RATIO: Record<string, number> = " + json.dumps(ratio) + ";", ""]
(ROOT / "src/data/photos.ts").write_text("\n".join(lines))
print(len(ids) - len(missing), "photos,", total // 1024, "KB; missing:", missing)
